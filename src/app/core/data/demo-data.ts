function createProductSvg(label: string, bg: string, fg: string): string {
  const safeLabel = label.slice(0, 3).toUpperCase();
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96"><rect width="96" height="96" rx="18" fill="${bg}"/><text x="48" y="55" text-anchor="middle" font-family="Inter,Arial,sans-serif" font-weight="700" font-size="24" fill="${fg}">${safeLabel}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

